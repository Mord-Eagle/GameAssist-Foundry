import * as esbuild from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

// ============================================================================
// [GAMEASSIST_BUILD:POLICY] BEGIN
// Section Title: Build inputs, outputs, and refusals
// -----------------------------------------------------------------------------
// mechsuit_section: {
//   codename: "GAMEASSIST_BUILD",
//   area: "POLICY",
//   title: "Build policy",
//   guarantees: ["One browser ESM bundle from src/main.ts to dist/gameassist.mjs."],
