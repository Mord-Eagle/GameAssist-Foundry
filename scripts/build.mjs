// esbuild is the only emitter. TypeScript remains a typecheck, not a second
// emit path. The generated banner tells maintainers not to edit dist/.
// -----------------------------------------------------------------------------
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");

const POLICY = {
  entry: path.join(root, "src", "main.ts"),
  outfile: path.join(root, "dist", "gameassist.mjs"),
  target: "es2022",
  banner: "/* GENERATED by scripts/build.mjs from src/main.ts. Do not edit. See __mechsuit__/build-output.md. */\n"
};
// --- Notes & Comments ---
// Changed (v0.1.0): lock the first esbuild emit path and generated-file notice.
