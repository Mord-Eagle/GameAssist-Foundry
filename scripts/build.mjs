// Narrative
// Validate the entry path by letting esbuild fail if it is missing. platform
// browser prevents Node built-ins from resolving. minify stays off so the
// first shell remains readable during live debugging.
// -----------------------------------------------------------------------------
/**
 * Bundles GameAssist client source into dist/gameassist.mjs.
 *
 * @returns {Promise<void>} Resolves after a successful emit.
 * @throws {Error} When esbuild reports a build failure.
 *
 * Side effects: creates dist/ and writes generated JavaScript plus a source map.
 */
async function bundle() {
  await mkdir(path.dirname(POLICY.outfile), { recursive: true });
  await esbuild.build({
    absWorkingDir: root,
    entryPoints: [POLICY.entry],
    outfile: POLICY.outfile,
    bundle: true,
    format: "esm",
    platform: "browser",
    target: POLICY.target,
    sourcemap: true,
    minify: false,
    logLevel: "info",
    banner: { js: POLICY.banner }
  });
  await writeFile(
    path.join(root, "dist", "GENERATED.md"),
    "# Generated output\n\nDo not edit files in dist/. Rebuild with `npm run build`.\n",
    "utf8"
  );
}

bundle().catch((error) => {
  console.error("[GAMEASSIST_BUILD] bundle failed");
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
